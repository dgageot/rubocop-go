func TestPointerHelper(t *testing.T) {
	t.Parallel()
	offenses := coptest.RunProgram(t, NewLintPointerHelper(), coptest.ProgramFiles{
		"go.mod":     "module example.test\n\ngo 1.26\nrequire github.com/aws/aws-sdk-go-v2 v0.0.0\nreplace github.com/aws/aws-sdk-go-v2 => ./aws\n",
		"aws/go.mod": "module github.com/aws/aws-sdk-go-v2\n\ngo 1.26\n",
		"aws/aws/pointer.go": `package aws
func String(v string) *string { return &v }
func Int32(v int32) *int32 { return &v }
func StringSlice(v []string) []*string { return nil }
func ToString(v *string) string { return *v }
`,
		"pointer.go": `package p
import sdk "github.com/aws/aws-sdk-go-v2/aws"
func f(s string) { _ = sdk.String(s); _ = sdk.Int32(1); _ = sdk.Int32(int32(len(s))) }
func allowed(s string) { _ = sdk.StringSlice([]string{s}); _ = sdk.ToString(&s) }
func shadowed(new int) { _ = sdk.String("x") }
func shadowedType(int32 int) { _ = sdk.Int32(1) }
`,
		"generated.go": `// Code generated by fixture. DO NOT EDIT.
package p
import "github.com/aws/aws-sdk-go-v2/aws"
var generated = aws.String("x")
`,
		"pkg/config/v1/frozen.go": `package v1
import "github.com/aws/aws-sdk-go-v2/aws"
var frozen = aws.String("x")
`,
		"other/other.go": `package aws
func String(s string) *string { return &s }
func f() { _ = String("x") }
`,
	})
	require.Len(t, offenses, 4)
	for _, offense := range offenses {
		assert.Equal(t, "Lint/PointerHelper", offense.CopName)
		assert.Contains(t, offense.Message, "conversion")
	}
}

func TestPointerHelperRequiresFunctionValueContext(t *testing.T) {
	t.Parallel()
	offenses := coptest.RunProgram(t, NewLintPointerHelper(), coptest.ProgramFiles{
		"go.mod":     "module example.test\n\ngo 1.26\nrequire github.com/aws/aws-sdk-go-v2 v0.0.0\nreplace github.com/aws/aws-sdk-go-v2 => ./aws\n",
		"aws/go.mod": "module github.com/aws/aws-sdk-go-v2\n\ngo 1.26\n",
		"aws/aws/pointer.go": `package aws
func String(v string) *string { return &v }
func Bool(v bool) *bool { return &v }
type Ternary int
func (Ternary) String() string { return "ternary" }
func (Ternary) Bool() bool { return true }
func (Ternary) Int32(v int32) *int32 { return &v }
`,
		"pointer.go": `package p
import sdk "github.com/aws/aws-sdk-go-v2/aws"
func consume(...*string) {}
func f(t sdk.Ternary) {
 _ = sdk.Ternary.String(t)
 _ = sdk.Ternary.Bool(t)
 _ = (sdk.Ternary.String)(t)
 _ = t.Int32(1)
 _ = (t.Int32)(1)
 sdk.String("discarded")
 (sdk.String("discarded with parentheses"))
 ((sdk.String)("parenthesized function"))
 go sdk.String("goroutine")
 go (sdk.String)("parenthesized goroutine")
 defer sdk.String("deferred")
 defer (sdk.String)("parenthesized defer")
 _ = sdk.String("value")
 _ = (sdk.String)("parenthesized value")
 _ = ((sdk.String("parenthesized call")))
 consume(sdk.String("nested statement"))
 go consume((sdk.String)("nested goroutine"))
 defer consume((sdk.String("nested defer")))
 consume(sdk.String(*sdk.String("nested helpers")))
 sdk.String(*sdk.String("nested discarded helper"))
 go sdk.String(*sdk.String("nested goroutine helper"))
 defer sdk.String(*sdk.String("nested deferred helper"))
 _ = sdk.Bool(true)
}
`,
	})
	require.Len(t, offenses, 12)
	var lines []int
	for _, offense := range offenses {
		assert.Equal(t, "Lint/PointerHelper", offense.CopName)
		lines = append(lines, offense.Pos.Line)
	}
	assert.ElementsMatch(t, []int{17, 18, 19, 20, 21, 22, 23, 23, 24, 25, 26, 27}, lines)
}

func TestPointerHelperRequiresScalarSignature(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, helper, call string
		want               int
	}{
		{"scalar", "func String(v string) *string { return &v }", `sdk.String("x")`, 1},
		{"aliases", "type Text = string; type Pointer = *Text; func String(v Text) Pointer { return &v }", `sdk.String("x")`, 1},
		{"generic explicit", "func String[T ~string](v T) *T { return &v }", `sdk.String[Name](Name("x"))`, 0},
		{"generic inferred", "func String[T ~string](v T) *T { return &v }", `sdk.String(Name("x"))`, 0},
		{"generic fixed signature", "func String[T any](v string) *string { return &v }", `sdk.String[int]("x")`, 0},
		{"wrong parameter", "func String(v int) *string { return nil }", "sdk.String(1)", 0},
		{"named parameter", "type Text string; func String(v Text) *string { return nil }", `sdk.String("x")`, 0},
		{"wrong result", "func String(v string) *int { return nil }", `sdk.String("x")`, 0},
		{"named result element", "type Text string; func String(v string) *Text { return nil }", `sdk.String("x")`, 0},
		{"named pointer", "type Pointer *string; func String(v string) Pointer { return nil }", `sdk.String("x")`, 0},
		{"nonpointer result", "func String(v string) string { return v }", `sdk.String("x")`, 0},
		{"multiple results", "func String(v string) (*string, error) { return &v, nil }", `sdk.String("x")`, 0},
		{"variadic", "func String(v ...string) *string { return &v[0] }", `sdk.String("x")`, 0},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			assignment := "_ = "
			if tc.name == "multiple results" {
				assignment = "_, _ = "
			}
			offenses := coptest.RunProgram(t, NewLintPointerHelper(), coptest.ProgramFiles{
				"go.mod":             "module example.test\n\ngo 1.26\nrequire github.com/aws/aws-sdk-go-v2 v0.0.0\nreplace github.com/aws/aws-sdk-go-v2 => ./aws\n",
				"aws/go.mod":         "module github.com/aws/aws-sdk-go-v2\n\ngo 1.26\n",
				"aws/aws/pointer.go": "package aws\n" + tc.helper + "\n",
				"pointer.go":         "package p\nimport sdk \"github.com/aws/aws-sdk-go-v2/aws\"\ntype Name string\nfunc f() { " + assignment + tc.call + " }\n",
			})
			assert.Len(t, offenses, tc.want)
		})
	}
}
