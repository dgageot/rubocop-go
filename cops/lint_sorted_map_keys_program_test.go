package cops

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/dgageot/rubocop-go/cop"
	"github.com/dgageot/rubocop-go/coptest"
)

func TestSortedMapKeysProgram(t *testing.T) {
	t.Parallel()
	c := NewLintSortedMapKeys(cop.WithScope(cop.Not(cop.UnderDir("legacy"))))
	require.NotSame(t, c, NewLintSortedMapKeys())
	offenses := coptest.RunProgram(t, c, coptest.ProgramFiles{
		"go.mod":                  "module example.test\n\ngo 1.26\n",
		"sample.go":               sortedMapKeysFixture,
		"internal/sample_test.go": sortedMapKeysFixture,
		"external/sample_test.go": strings.Replace(sortedMapKeysFixture, "package p", "package p_test", 1),
		"legacy/sample.go":        sortedMapKeysFixture,
		"generated/sample.go":     "// Code generated by test; DO NOT EDIT.\n" + sortedMapKeysFixture,
	})
	require.Len(t, offenses, 3)
	for _, offense := range offenses {
		assert.Equal(t, "Lint/SortedMapKeys", offense.CopName)
		assert.Greater(t, offense.End.Offset, offense.Pos.Offset)
	}
}
