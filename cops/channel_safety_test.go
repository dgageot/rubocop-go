const cancellationSafeResultSendFixture = `package p
import "context"
func f(ctx context.Context) { ch := make(chan int); go func(){ ch <- 1 }(); select { case <-ctx.Done(): return; case <-ch: } }
`

const nonblockingChannelReplacementFixture = `package p
func f(c chan int) { select { case c <- 1: default: <-c; c <- 1 } }
`

func TestChannelSafetyFactories(t *testing.T) {
	t.Parallel()
	for _, tc := range channelSafetyCases() {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			first, second := tc.new(), tc.new()
			require.NotSame(t, first, second)
			file := tc.file()
			assert.Nil(t, file.Scope)
			assert.True(t, file.NeedsTypes())
			assert.Equal(t, file.Meta, first.Meta)
			assert.Empty(t, coptest.Run(t, file, tc.source), "missing type information")

			for _, option := range []struct {
				name string
				opt  cop.FuncOption
				want int
			}{
				{"current language", cop.WithMinGoVersion("go1.26"), 1},
				{"newer language", cop.WithMinGoVersion("go1.27"), 0},
				{"current stdlib", cop.WithMinStdlibVersion("go1.26"), 1},
				{"newer stdlib", cop.WithMinStdlibVersion("go1.27"), 0},
				{"severity", func(c *cop.Func) { c.Meta.Severity = cop.Error }, 1},
			} {
				t.Run(option.name, func(t *testing.T) {
					check := tc.new(option.opt)
					p := &prog.Pass{Cop: check, Program: channelSafetyTestProgram(t, "sample.go", tc.source)}
					check.Check(p)
					assert.Len(t, p.Offenses(), option.want)
					for _, offense := range p.Offenses() {
						assert.Equal(t, check.Severity(), offense.Severity)
					}
				})
			}
		})
	}
}

func TestChannelSafetyConsumerExclusions(t *testing.T) {
	t.Parallel()
	for _, tc := range channelSafetyCases() {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			files := coptest.ProgramFiles{
				"go.mod":              "module example.test\n\ngo 1.26\n",
				"active/sample.go":    tc.source,
				"legacy/sample.go":    tc.source,
				"generated/sample.go": "// Code generated by fixture; DO NOT EDIT.\n" + tc.source,
			}
			assert.Len(t, coptest.RunProgram(t, tc.new(), files), 2)
			check := tc.new(cop.WithScope(cop.Not(cop.UnderDir("legacy"))))
			offenses := coptest.RunProgram(t, check, files)
			require.Len(t, offenses, 1)
			assert.True(t, strings.HasSuffix(filepath.ToSlash(offenses[0].Pos.Filename), "/active/sample.go"))
		})
	}
}

func TestChannelSafetyProductionOnly(t *testing.T) {
	t.Parallel()
	for _, tc := range channelSafetyCases() {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			for _, file := range []struct {
				name, prefix string
				want         int
			}{
				{"sample.go", "", 1},
				{"sample_test.go", "", 0},
				{"generated.go", "// Code generated by fixture; DO NOT EDIT.\n", 0},
			} {
				t.Run(file.name, func(t *testing.T) {
					check := tc.new()
					p := &prog.Pass{Cop: check, Program: channelSafetyTestProgram(t, file.name, file.prefix+tc.source)}
					check.Check(p)
					assert.Len(t, p.Offenses(), file.want)
				})
			}
		})
	}
}

type channelSafetyCase struct {
	name   string
	new    func(...cop.FuncOption) *prog.Func
	file   func(...cop.FuncOption) *cop.Func
	source string
}

func channelSafetyCases() []channelSafetyCase {
	return []channelSafetyCase{
		{"CancellationSafeResultSend", NewLintCancellationSafeResultSend, newCancellationSafeResultSendFile, cancellationSafeResultSendFixture},
		{"NonblockingChannelReplacement", NewLintNonblockingChannelReplacement, newNonblockingChannelReplacementFile, nonblockingChannelReplacementFixture},
	}
}

func channelSafetyTestProgram(t *testing.T, filename, source string) *prog.Program {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, source, parser.ParseComments)
	require.NoError(t, err)
	info := &types.Info{
		Types: make(map[ast.Expr]types.TypeAndValue), Defs: make(map[*ast.Ident]types.Object),
		Uses: make(map[*ast.Ident]types.Object), Selections: make(map[*ast.SelectorExpr]*types.Selection),
	}
	cfg := types.Config{Importer: importer.Default(), GoVersion: "go1.26"}
	pkg, err := cfg.Check("example.test", fset, []*ast.File{file}, info)
	require.NoError(t, err)
	return &prog.Program{
		Fset: fset, Packages: []*packages.Package{{Types: pkg, TypesInfo: info, Syntax: []*ast.File{file}}},
	}
}

func testChannelSafetySuppressions(t *testing.T, check prog.Cop, source string) {
	t.Helper()
	dir := t.TempDir()
	// The runner resolves relative module patterns from its current directory.
	t.Chdir(dir)
	for name, data := range map[string]string{
		"go.mod":               "module example.test\n\ngo 1.26\n",
		"reported/sample.go":   source,
		"inline/sample.go":     strings.ReplaceAll(source, "// offense", "//rubocop:disable "+check.Name()),
		"suppressed/sample.go": "//rubocop:disable-file " + check.Name() + "\n" + source,
	} {
		require.NoError(t, os.MkdirAll(filepath.Dir(name), 0o700))
		require.NoError(t, os.WriteFile(name, []byte(data), 0o600))
	}
	var output bytes.Buffer
	r := runner.New(nil, config.DefaultConfig(), &output).WithProgramCops([]prog.Cop{check})
	count, err := r.Run([]string{"."})
	require.NoError(t, err)
	assert.Equal(t, 1, count, output.String())
	assert.Contains(t, output.String(), filepath.Join("reported", "sample.go"))
	assert.NotContains(t, output.String(), filepath.Join("inline", "sample.go"))
	assert.NotContains(t, output.String(), filepath.Join("suppressed", "sample.go"))
}
