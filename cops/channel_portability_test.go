func portableCopFixtures() []struct {
	new func(...cop.FuncOption) *prog.Func
	src string
} {
	return []struct {
		new func(...cop.FuncOption) *prog.Func
		src string
	}{
		{NewLintCancellationLoop, "package p\nimport \"context\"\nfunc f(ctx context.Context) { for { select { case <-ctx.Done(): break } } }\n"},
		{NewLintClosedChannelLoop, "package p\nfunc f(ch chan int) { for { _, ok := <-ch; if !ok { continue } } }\n"},
		{NewLintChannelStateCheck, "package p\nfunc f(ch chan int) { if len(ch) > 0 { <-ch } }\n"},
		{NewLintCancellationSafeResultSend, "package p\nimport \"context\"\nfunc f(ctx context.Context) { ch := make(chan int); go func() { ch <- 1 }(); select { case <-ctx.Done(): return; case <-ch: } }\n"},
		{NewLintNonblockingChannelReplacement, "package p\nfunc f(ch chan int) { select { case ch <- 1: default: <-ch; ch <- 1 } }\n"},
		{NewLintSlicesConcat, "package p\nfunc f(a, b []int) []int { return append(append([]int(nil), a...), b...) }\n"},
	}
}

func TestPortableCopsRunnerPolicy(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	cfg := config.DefaultConfig()
	var checks []prog.Cop
	for _, fixture := range portableCopFixtures() {
		check := fixture.new(cop.WithScope(cop.Not(cop.UnderDir("legacy"))))
		checks = append(checks, check)
		cfg.Cops[check.Name()] = config.CopConfig{Severity: "error"}
		for prefix, source := range map[string]string{
			"active":     fixture.src,
			"legacy":     fixture.src,
			"generated":  "// Code generated by fixture; DO NOT EDIT.\n" + fixture.src,
			"suppressed": "//rubocop:disable-file " + check.Name() + "\n" + fixture.src,
			"inline":     strings.ReplaceAll(fixture.src, " }\n", " } //rubocop:disable "+check.Name()+"\n"),
		} {
			path := filepath.Join(prefix, strings.TrimPrefix(check.Name(), "Lint/"), "sample.go")
			require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o700))
			require.NoError(t, os.WriteFile(path, []byte(source), 0o600))
		}
	}
	require.NoError(t, os.WriteFile("go.mod", []byte("module example.test\n\ngo 1.26\n"), 0o600))
	var output bytes.Buffer
	r := runner.New(nil, cfg, &output).WithProgramCops(checks)
	r.Reporter = runner.NewJSONReporter(&output)
	count, err := r.Run([]string{"."})
	require.NoError(t, err)
	require.Equal(t, len(checks), count, output.String())
	var result struct {
		Offenses []struct {
			Cop, Severity, File string
			Line, Column        int
			EndColumn           int `json:"end_column"`
		}
	}
	require.NoError(t, json.Unmarshal(output.Bytes(), &result))
	seen := make(map[string]bool)
	for _, offense := range result.Offenses {
		assert.False(t, seen[offense.Cop], offense.Cop)
		seen[offense.Cop] = true
		assert.Equal(t, "error", offense.Severity)
		assert.Contains(t, filepath.ToSlash(offense.File), "/active/")
		assert.Positive(t, offense.Line)
		assert.Greater(t, offense.EndColumn, offense.Column)
	}
	assert.Len(t, seen, len(checks))
}

func TestPortableCopConstructorsAreIndependent(t *testing.T) {
	t.Parallel()
	for _, fixture := range portableCopFixtures() {
		t.Run(fixture.new().Name(), func(t *testing.T) {
			t.Parallel()
			restricted := fixture.new(cop.WithScope(func(*cop.Pass) bool { return false }))
			assert.Empty(t, coptest.RunProgram(t, restricted, coptest.ProgramFiles{"sample.go": fixture.src}))
			require.Len(t, coptest.RunProgram(t, fixture.new(), coptest.ProgramFiles{"sample.go": fixture.src}), 1)
		})
	}
}

func TestCancellationLoopTestPackages(t *testing.T) {
	t.Parallel()
	src := "package p\nimport \"context\"\nfunc f(ctx context.Context) { for { select { case <-ctx.Done(): continue } } }\n"
	offenses := coptest.RunProgram(t, NewLintCancellationLoop(), coptest.ProgramFiles{
		"regular/sample.go":       src,
		"internal/sample.go":      "package p\n",
		"internal/sample_test.go": src,
		"external/sample.go":      "package p\n",
		"external/sample_test.go": strings.Replace(src, "package p", "package p_test", 1),
		"testonly/sample_test.go": src,
	})
	require.Len(t, offenses, 4)
}
